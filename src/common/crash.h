// =============================================================================
//  crash.h - 崩溃自诊断
//
//  为什么需要它：
//    被控端/远控端是 GUI 程序，一旦有未捕获的 C++ 异常或访问越界，Windows
//    的默认行为是弹一个"程序已停止工作"然后消失——用户只看到"闪退"，
//    完全不知道发生了什么（这正是本项目的真实故障现场）。
//
//    装上这个处理器后，任何崩溃都会：
//      1) 往 exe 目录的 crash.log 追加一条可读的中文说明，
//         未捕获 C++ 异常还会打印类型名、what() 和 error_code；
//      2) 往 exe 目录写一份 minidump（crash_<tag>_<pid>.dmp），
//         可以用 tools/minidump_info.py 精确还原调用栈；
//      3) 不再弹系统错误框，直接安静退出（退出码 3/4 区分异常类型）。
//
//  注意：崩溃路径上只允许用 Win32 API。CRT 的锁/堆在崩溃时可能已经不可用，
//  所以这里不用 std::string 拼接、不用 printf、不碰日志模块的互斥量。
// =============================================================================
#pragma once

namespace ms::crash {

// 安装崩溃处理器。appTag 会出现在日志和转储文件名里（"host" / "client"）。
void install(const char* appTag);

// crash.log 的完整路径（UTF-8），仅用于启动日志里提示用户。
const char* log_path();

} // namespace ms::crash
